#!/usr/bin/env bash
set -euo pipefail
INFRA_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$INFRA_DIR"
if [[ $# -gt 1 || ( $# -eq 1 && "$1" != "--generate-only" ) ]]; then
  echo 'Usage: bash infra/scripts/db-allowlist.sh [--generate-only]' >&2
  exit 1
fi
# Directory mount makes atomic file replacement visible inside PostgreSQL.
python3 - "$INFRA_DIR/db" <<'PY'
import ipaddress
import os
import pathlib
import sys
import tempfile

directory = pathlib.Path(sys.argv[1])
rules = ['# Generated by infra/scripts/db-allowlist.sh; edit allowed-ips.txt.',
         'local all all trust', 'local replication all trust']
seen = set()
for number, raw in enumerate((directory / 'allowed-ips.txt').read_text().splitlines(), 1):
    value = raw.split('#', 1)[0].strip()
    if not value:
        continue
    try:
        network = ipaddress.ip_network(value, strict=True)
    except ValueError:
        sys.exit(f'Invalid IP/CIDR at allowed-ips.txt:{number}')
    if network.prefixlen == 0:
        sys.exit(f'Unrestricted network forbidden at allowed-ips.txt:{number}')
    if network not in seen:
        rules.append(f'host all all {network} scram-sha-256')
        seen.add(network)
rules += ['host all all samenet scram-sha-256',
          'host all all 0.0.0.0/0 reject', 'host all all ::/0 reject']
fd, temporary = tempfile.mkstemp(prefix='.pg_hba.', dir=directory)
try:
    with os.fdopen(fd, 'w') as output:
        output.write('\n'.join(rules) + '\n')
    os.chmod(temporary, 0o644)
    os.replace(temporary, directory / 'pg_hba.conf')
finally:
    if os.path.exists(temporary):
        os.unlink(temporary)
PY
if [[ "${1:-}" == "--generate-only" ]]; then exit 0; fi
docker compose exec -T db sh -eu -c '
  errors=$(psql -X -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Atc "SELECT count(*) FROM pg_hba_file_rules WHERE error IS NOT NULL")
  [ "$errors" = 0 ] || { echo "Invalid pg_hba.conf; not reloaded" >&2; exit 1; }
  result=$(psql -X -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Atc "SELECT pg_reload_conf()")
  [ "$result" = t ]
'
echo 'PostgreSQL allowlist reloaded; existing connections are retained.'
